"""
src/patch_review.py
───────────────────
Patch Review State Machine (no Qt dependencies).

Manages lifecycle and review state of patches generated by Planner in review mode:
    pending -> accepted | rejected
    accepted -> undo (restores pre-patch bytes byte-for-byte in LIFO order)

Safety Rules:
- S2 patches cannot be accepted (suggestion-only).
- Gate-failed patches cannot be accepted (suggestion-only).
- Rejecting leaves the file untouched.
- Undo restores the exact byte-for-byte state prior to patch application.
"""

from __future__ import annotations

import os
from enum import Enum
from typing import List, Optional, Any, Dict
from dataclasses import dataclass, field

from diagnostic import Patch, Diagnostic


class PatchStatus(str, Enum):
    PENDING = "pending"
    ACCEPTED = "accepted"
    REJECTED = "rejected"


class InvalidTransitionError(ValueError):
    """Raised when an illegal state transition is attempted on a patch."""
    pass


@dataclass
class ReviewablePatch:
    """Wrapper around a Planner Patch tracking review state."""
    patch_id: int
    patch: Patch
    status: PatchStatus = PatchStatus.PENDING
    pre_patch_bytes: Optional[bytes] = None
    applied_bytes: Optional[bytes] = None
    accepted_timestamp: Optional[str] = None

    @property
    def safety_level(self) -> str:
        return getattr(self.patch, "safety_level", "S0")

    @property
    def suggestion_only(self) -> bool:
        return getattr(self.patch, "suggestion_only", False)

    @property
    def gate_results(self) -> list:
        return getattr(self.patch, "gate_results", [])

    @property
    def failing_gate(self) -> Optional[str]:
        vr = getattr(self.patch, "verify_result", None)
        if vr:
            fg = getattr(vr, "failing_gate", None)
            if fg:
                return fg
        for g in self.gate_results:
            if isinstance(g, dict) and (g.get("status") == "failed" or g.get("passed") is False):
                return g.get("gate")
            elif hasattr(g, "passed") and not g.passed:
                return getattr(g, "gate_name", getattr(g, "gate", "verification_gate"))
        return None

    @property
    def passed_gates(self) -> bool:
        vr = getattr(self.patch, "verify_result", None)
        if vr is not None:
            return bool(getattr(vr, "passed", False))
        return self.failing_gate is None

    def can_accept(self) -> tuple[bool, str]:
        """
        Check if the patch is eligible to be accepted.
        Returns (can_accept: bool, reason: str).
        """
        if self.status != PatchStatus.PENDING:
            return False, f"Patch is in '{self.status.value}' state, must be '{PatchStatus.PENDING.value}'."
        if not self.passed_gates:
            return False, f"Verification gate failed ({self.failing_gate or 'verification_gate'}); cannot accept."
        return True, "OK"


class PatchReviewSession:
    """
    Session coordinating the review, accept, reject, and undo of patches on a file.
    Appends review decisions (accepted, rejected, undone) to data/patch_feedback.jsonl.
    """
    def __init__(
        self,
        file_path: str,
        patches: Optional[List[Patch]] = None,
        patch_feedback_file: Optional[str] = None,
    ):
        self.file_path = file_path
        self.patches: List[ReviewablePatch] = []
        # LIFO stack storing (ReviewablePatch, pre_patch_bytes)
        self._undo_stack: List[tuple[ReviewablePatch, bytes]] = []
        self.patch_feedback_file = patch_feedback_file

        if patches:
            for p in patches:
                self.add_patch(p)

    def add_patch(self, patch: Patch) -> ReviewablePatch:
        rp = ReviewablePatch(patch_id=len(self.patches) + 1, patch=patch)
        self.patches.append(rp)
        return rp

    def get_patch(self, patch_id: int) -> ReviewablePatch:
        for p in self.patches:
            if p.patch_id == patch_id:
                return p
        raise KeyError(f"Patch ID {patch_id} not found.")

    def accept(self, patch_id: int) -> bool:
        """
        Accept and apply patch to file_path.
        Records pre-patch bytes onto undo stack and logs decision.
        """
        rp = self.get_patch(patch_id)
        can, reason = rp.can_accept()
        if not can:
            raise InvalidTransitionError(f"Cannot accept patch {patch_id}: {reason}")

        # Capture pre-patch bytes
        if os.path.exists(self.file_path):
            with open(self.file_path, "rb") as f:
                pre_bytes = f.read()
        else:
            pre_bytes = b""

        rp.pre_patch_bytes = pre_bytes

        # Also write backup file (.bak) matching planner convention
        bak_file = self.file_path + ".bak"
        with open(bak_file, "wb") as f:
            f.write(pre_bytes)

        # Write patched source
        with open(self.file_path, "w", encoding="utf-8") as f:
            f.write(rp.patch.patched_source)

        with open(self.file_path, "rb") as f:
            rp.applied_bytes = f.read()

        import datetime
        now_ts = datetime.datetime.now(datetime.timezone.utc).isoformat()
        rp.accepted_timestamp = now_ts
        rp.status = PatchStatus.ACCEPTED
        self._undo_stack.append((rp, pre_bytes))

        # Log decision to append-only patch feedback log
        try:
            from feedback_store import log_patch_decision, DEFAULT_PATCH_FEEDBACK_FILE
            log_file = self.patch_feedback_file or DEFAULT_PATCH_FEEDBACK_FILE
            log_patch_decision(
                file_path=self.file_path,
                patch=rp.patch,
                decision="accepted",
                pre_patch_bytes=pre_bytes,
                log_file=log_file,
                patch_id=rp.patch_id,
            )
        except Exception:
            pass

        return True

    def reject(self, patch_id: int) -> bool:
        """
        Reject patch. Leaves file_path completely untouched and logs decision.
        """
        rp = self.get_patch(patch_id)
        if rp.status != PatchStatus.PENDING:
            raise InvalidTransitionError(f"Cannot reject patch {patch_id}: already in '{rp.status.value}' state.")

        rp.status = PatchStatus.REJECTED

        # Log decision to append-only patch feedback log
        try:
            from feedback_store import log_patch_decision, DEFAULT_PATCH_FEEDBACK_FILE
            log_file = self.patch_feedback_file or DEFAULT_PATCH_FEEDBACK_FILE
            pre_bytes = open(self.file_path, "rb").read() if os.path.exists(self.file_path) else b""
            log_patch_decision(
                file_path=self.file_path,
                patch=rp.patch,
                decision="rejected",
                pre_patch_bytes=pre_bytes,
                log_file=log_file,
                patch_id=rp.patch_id,
            )
        except Exception:
            pass

        return True

    def undo(self, patch_id: Optional[int] = None) -> ReviewablePatch:
        """
        Undo the most recently accepted patch in LIFO order.
        If patch_id is provided, verifies that it is the top of the LIFO stack;
        otherwise raises InvalidTransitionError refusing an out-of-order undo.
        Restores the file byte-for-byte to its state before that patch.
        Appends an 'undone' record referencing the original accept.
        """
        if not self._undo_stack:
            raise IndexError("Undo stack is empty: no accepted patches to undo.")

        if patch_id is not None and self._undo_stack[-1][0].patch_id != patch_id:
            top_id = self._undo_stack[-1][0].patch_id
            raise InvalidTransitionError(
                f"Cannot undo patch {patch_id} out of order: only the most recently accepted "
                f"patch (ID {top_id}) can be undone in LIFO order."
            )

        rp, pre_bytes = self._undo_stack.pop()

        # Restore file bytes byte-for-byte
        with open(self.file_path, "wb") as f:
            f.write(pre_bytes)

        # Also sync backup file if stack has further history
        bak_file = self.file_path + ".bak"
        if self._undo_stack:
            prev_pre = self._undo_stack[-1][1]
            with open(bak_file, "wb") as f:
                f.write(prev_pre)
        elif os.path.exists(bak_file):
            with open(bak_file, "wb") as f:
                f.write(pre_bytes)

        orig_timestamp = rp.accepted_timestamp
        rp.status = PatchStatus.PENDING

        # Log decision to append-only patch feedback log (full history preserved)
        try:
            from feedback_store import log_patch_decision, DEFAULT_PATCH_FEEDBACK_FILE
            log_file = self.patch_feedback_file or DEFAULT_PATCH_FEEDBACK_FILE
            log_patch_decision(
                file_path=self.file_path,
                patch=rp.patch,
                decision="undone",
                pre_patch_bytes=rp.applied_bytes,
                log_file=log_file,
                patch_id=rp.patch_id,
                ref_patch_id=rp.patch_id,
                ref_timestamp=orig_timestamp,
            )
        except Exception:
            pass

        return rp

    @property
    def can_undo(self) -> bool:
        return len(self._undo_stack) > 0

    @property
    def pending_count(self) -> int:
        return sum(1 for p in self.patches if p.status == PatchStatus.PENDING)

    @property
    def accepted_count(self) -> int:
        return sum(1 for p in self.patches if p.status == PatchStatus.ACCEPTED)

    @property
    def rejected_count(self) -> int:
        return sum(1 for p in self.patches if p.status == PatchStatus.REJECTED)
